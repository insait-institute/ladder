ConfigT = TypeVar("ConfigT", bound=Config)


class ConfigurableMeta(ABCMeta):
    @functools.lru_cache(maxsize=None, typed=True)  # noqa: B019
    def __getitem__(cls, config_type):  # noqa: N805
        """Configurable[ModelConfig] (or Model[ModelConfig]): the class with its config class set."""
        if not isinstance(cls.ConfigT, TypeVar):
            raise TypeError(f"{cls.__name__} already has a config class: {cls.ConfigT}")
        new_cls = parametrize(cls, (config_type,))
        # Set after creation, so only named subclasses (class Model(Configurable[ModelConfig])) register
        new_cls.ConfigT = config_type
        return new_cls


class Configurable(metaclass=ConfigurableMeta):
    """A class built from a config, e.g. `class Model(Configurable[ModelConfig])`, which has
    `Model.ConfigT is ModelConfig`. A class whose ConfigT is still a TypeVar can be subscripted again."""

    ConfigT = ConfigT

    def __init__(self, config: ConfigT):
        if not config.__class__ == self.ConfigT:
            raise TypeError(
                f"{self.__class__}.__init__() expects an instance of "
                f"{self.ConfigT}, but got {config.__class__}"
            )
        self._config = config

    @property
    def config(self) -> ConfigT:
        return self._config

    @classmethod
    def from_kwargs(cls, **kwargs) -> "Configurable":
        config = cls.ConfigT(**kwargs)
        return cls(config)

    def __init_subclass__(cls, **kwargs) -> None:
        super().__init_subclass__(**kwargs)
        # Don't add any classes whose config class is still a TypeVar to the registry
        if not isinstance(cls.ConfigT, TypeVar) and issubclass(cls.ConfigT, Config):
            AutoRecordsManager.add_to_records(cls)


class AutoRecordsManager:
    CONFIGURABLE_CLS_PATH_TO_CONFIG_CLS: Dict[str, Type[Config]] = {}
    CONFIGURABLE_CLS_PATH_TO_CONFIGURABLE_CLS: Dict[str, Type[Configurable]] = {}

    @classmethod
    def add_to_records(cls, ConfigurableT: Type[Configurable]):  # noqa: N803
        assert issubclass(ConfigurableT, Configurable), ConfigurableT

        ConfigType: Type[Config] = ConfigurableT.ConfigT

        configurable_class_path = f"{ConfigurableT.__module__}.{ConfigurableT.__qualname__}"

        if configurable_class_path in cls.CONFIGURABLE_CLS_PATH_TO_CONFIG_CLS:
            # Only print warning if running in interactive shell or notebook, to allow for re-executing cells
            if is_interactive_py():
                print(
                    f"WARNING: Duplicate registration of class {configurable_class_path}. Deleting old records"
                )
            else:
                raise ValueError(f"Class {configurable_class_path} already registered. System Error.")

        cls.CONFIGURABLE_CLS_PATH_TO_CONFIG_CLS[configurable_class_path] = ConfigType
        cls.CONFIGURABLE_CLS_PATH_TO_CONFIGURABLE_CLS[configurable_class_path] = ConfigurableT

    @classmethod
    def config_cls_from_configurable_path(cls, configurable_class_path: str) -> Type[Config]:
        if configurable_class_path == "" or "." not in configurable_class_path:
            raise ValueError(
                f"You need to provide the complete path to the target Configurable class, "
                f"got '{configurable_class_path}'"
            )

        cls._maybe_import_class_from_module(configurable_class_path)

        klass = cls.CONFIGURABLE_CLS_PATH_TO_CONFIG_CLS.get(configurable_class_path, None)

        if klass is None:
            expected_keys = list(cls.CONFIGURABLE_CLS_PATH_TO_CONFIG_CLS.keys())
            raise ValueError(
                f"AutoConfig does not recognize the class path: '{configurable_class_path}'. Expected one of the following:"
                f"\n{pprint.pformat(expected_keys, indent=2)}\nTo enable AutoConfig initialization, make sure the "
                f"target class path points to a class that inherits from Configurable or to a Config class that "
                f"is provided as type argument to a Configurable. Also make sure the python module where "
                f"the Configurable class is defined is actually imported in your program."
            )
        assert klass is not None  # Help mypy
        return klass

    @classmethod
    def configurable_cls_from_configurable_path(cls, configurable_class_path: str) -> Type[Configurable]:
        if configurable_class_path == "" or "." not in configurable_class_path:
            raise ValueError(
                f"You need to provide the complete path to the target Configurable class, "
                f"got '{configurable_class_path}'"
            )

        cls._maybe_import_class_from_module(configurable_class_path)

        klass = cls.CONFIGURABLE_CLS_PATH_TO_CONFIGURABLE_CLS.get(configurable_class_path, None)

        if klass is None:
            expected_keys = list(cls.CONFIGURABLE_CLS_PATH_TO_CONFIGURABLE_CLS.keys())
            raise ValueError(
                f"AutoConfig does not recognize the class path: '{configurable_class_path}'. Expected one of the following:"
                f"\n{pprint.pformat(expected_keys, indent=2)}\nTo enable AutoConfig initialization, make sure the "
                f"target class path points to a class that inherits from Configurable or to a Config class that "
                f"is provided as type argument to a Configurable. Also make sure the python module where "
                f"the Configurable class is defined is actually imported in your program."
            )
        assert klass is not None  # Help mypy
        return klass

    @classmethod
    def configurable_cls_from_config(cls, config: Config) -> Type[Configurable]:
        return cls.configurable_cls_from_configurable_path(config.autoclass)

    @classmethod
    def _maybe_import_class_from_module(cls, class_path: str) -> None:
        """
        Import a class using its full path. Useful when using YAML configs - allows for automatically
        selecting Config / Configurable classes without explicitly importing them in the executable
        script. If the Configurable class hasn't been imported, it won't be registered and Auto won't work
        """
        if class_path in cls.CONFIGURABLE_CLS_PATH_TO_CONFIGURABLE_CLS:
            # Class already known and registered - no need to import
            return

        assert "." in class_path, class_path
        module_path, class_name = class_path.rsplit(".", maxsplit=1)
        try:
            module = importlib.import_module(module_path)
        except (ImportError, ModuleNotFoundError) as exc:
            message = f"Can't import module {module_path}. Error: {exc}"
            raise type(exc)(message) from exc

        klass = getattr(module, class_name)

        if not issubclass(klass, Configurable):
            raise TypeError(f'Target class {class_path} must point to a subclass of Configurable')


def is_interactive_py() -> bool:
    return hasattr(sys, 'ps1')


def _update_dict_of_maybe_configs(dict_1: Dict[str, Any], dict_2: Dict[str, Any]) -> Dict[str, Any]:
    """
    Updates dict_1 with dict_2. Supports Config as value
    Wherever there are matching keys, if both values are convertible to dict, then conversion is
    done and the dicts are merged. Otherwise, value_2 overwrites value_1

    Example 1:
        dict_1: {'a': 5, 'b': {'c': 6, 'd': 7}}
        dict_2: {'b': {'e': 3}}
        result: {'a': 5, 'b': {'c': 6, 'd': 7, 'e': 3}}
    Example 2:
        dict_1: {'a': 5, 'b': {'c': 6, 'd': 7}}
        dict_2: {'b': {'d': {'e': 3}}}
        result: {'a': 5, 'b': {'c': 6, 'd': {'e': 3}}}
    """
    dict_1 = dict(dict_1)
    for key, value_2 in dict_2.items():
        value_1: Any = dict_1.get(key, {})

        # Convert Config -> Dict[str, Any]
        if isinstance(value_1, Config):
            value_1 = value_1.as_json()

        # Convert Config -> Dict[str, Any]
        if isinstance(value_2, Config):
            value_2 = value_2.as_json()

        if isinstance(value_1, dict) and isinstance(value_2, dict):
            dict_1[key] = _update_dict_of_maybe_configs(value_1, value_2)
        # If either of the values isn't a Dict, overwrite value_1 directly
        else:
            dict_1[key] = value_2
    return dict_1
