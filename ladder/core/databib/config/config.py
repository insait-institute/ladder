_FROZEN_DEFAULTS_TYPE_MAPPING: Dict[str, type] = {
    'dict': frozendict,
    'list': tuple,
    'OrderedDict': FrozenOrderedDict,
    'set': frozenset,
}

_FROZEN_TYPE_MAPPING: Dict[str, type] = {
    'set': frozenset,
}


class ConfigMeta(DataclassMeta):
    def __new__(mcs, name, bases, attrs, **kwargs):  # noqa: N804
        mcs._assert_config_is_non_generic(name, bases)
        mcs._assert_post_init_calls_super(name, attrs)
        mcs._assert_class_does_not_overwrite_autoclass_key(name, attrs)

        attrs = mcs._replace_default_values_with_frozen_types(attrs)

        new_cls = super().__new__(mcs, name, bases, attrs, **kwargs)
        new_dataclass = dataclasses.dataclass(new_cls, init=False, frozen=True, repr=False)
        new_dataclass._prevent_forbidden_type_annotations()  # noqa: SLF001

        # frozen=True causes __setattr__ to get generated (and doesn't allow it to be defined on the class)
        # Override the one generated by the dataclass to get around that restriction.
        new_dataclass.__setattr__ = new_dataclass.__config_setattr__

        return new_dataclass

    @staticmethod
    def _assert_post_init_calls_super(name, attrs):
        """Check the __post_init__ definition of the subclass and make sure it calls super().__post_init__()"""
        if name == "Config" or "__post_init__" not in attrs:
            return
        if "super().__post_init__()" not in inspect.getsource(attrs["__post_init__"]):
            raise RuntimeError(f"{name}.__post_init__ method is missing a call to super().__post_init__()")

    @staticmethod
    def _assert_config_is_non_generic(name, bases):
        """
        Make sure that the Config subclass doesn't inherit from Generic.
        This functionality is not supported and causes multiple problems
        """
        # AutoConfig[X] is the one parametrized config class
        if name == "AutoConfig" or name.startswith("AutoConfig["):
            return
        for base in bases:
            if base is Generic or getattr(base, "__parameters__", False):
                raise TypeError(f"Generic config classes are not allowed. Please make {name} non-generic.")

    @staticmethod
    def _assert_class_does_not_overwrite_autoclass_key(name, attrs):
        """
        Make sure that the special `autoclass` key of AutoConfig is not accidentally overwritten by a Config subclass
        """
        if name == "Config":
            return
        annotations = attrs.get("__annotations__", {})
        autoclass_key = "autoclass"
        if autoclass_key in annotations:
            raise ValueError(
                f"Class {name} defines attribute {autoclass_key}, which is a reserved attribute. Please rename."
            )

    @staticmethod
    def _replace_default_values_with_frozen_types(attrs) -> Dict[str, Type]:
        """
        Replace the mutable default values in a subclass of Config with their immutable counterparts.
        Note that we are replacing only the default values, not the type annotations themselves.
        """
        annotations = attrs.get("__annotations__", {})
        return {
            key: _FROZEN_DEFAULTS_TYPE_MAPPING[type(value).__name__](value)
            if key in annotations and type(value).__name__ in _FROZEN_DEFAULTS_TYPE_MAPPING
            else value
            for key, value in attrs.items()
        }

    def _define_dict_and_list_attribute_classes(cls):  # noqa: N805
        """
        Overloading DataclassMeta._define_dict_and_list_attribute_classes

        [IMPORTANT]: Suppose we have a Config
        ```
        @dataclass
        class MyConfig(Config):
            my_field: Dict[str, int]
        ```
        The values for my_field will always be cast to `ConfigDict[int]` inside `Config.__init__()`
        However, the type `ConfigDict[int]` doesn't exist before we try to create an instance of
        `MyConfig`. This is problematic because:
          1. We cannot properly unpickle such classes when using multiprocessing. In particular, the
              class `MyConfig` will be known to the subprocess since the class will be imported.
              However, `ConfigDict[int]` will be undefined, since the subprocess hasn't created
              an instance of `MyConfig` before it tries to unpickle it
          2. If the types inside `Dict` are not allowed in `ConfigDict`, error will be raised only
              when we try to create an instance, instead of at class definition time
        To resolve these problems, here we define all the equivalent `ConfigDict` and `ConfigList`
        classes needed for the new dataclass attributes
        """
        import ladder.core.databib.config.config_iterables as config_iterables  # pylint: disable=cyclic-import

        # NOTE: At this point, @dataclass has been applied so `__dataclass_fields__` is not the
        # absolute source of truth for dataclass attributes. `__annotations__` gives us the fields added in
        # this class definition, while `__dataclass_fields__` gives us the fields defined by the parents.
        # We check both to also cover any transitive updates on parent class attributes, e.g. if
        # called by `__getitem__`
        annotations = getattr(cls, '__annotations__', {})
        dataclass_fields = getattr(cls, '__dataclass_fields__', {})
        fields = {**annotations, **{field.name: field.type for field in dataclass_fields.values()}}

        for field_name, field_type in fields.items():
            if annotation_is_dict(field_type):
                _, DValueT = get_dict_annotation_type_args(field_type)
                try:
                    config_iterables.ConfigDict[DValueT]
                except TypeError as exc:
                    # Provide more informative error message when DValueT not allowed
                    message = f"Cannot cast {cls.__name__}.{field_name} to ConfigDict[{DValueT}].\n{exc}"
                    raise TypeError(message) from exc
            if annotation_is_list(field_type):
                LValueT: Type = get_list_annotation_type_args(field_type)[0]
                try:
                    config_iterables.ConfigList[LValueT]
                except TypeError as exc:
                    # Provide more informative error message when DValueT not allowed
                    message = f"Cannot cast {cls.__name__}.{field_name} to ConfigList[{LValueT}].\n{exc}"
                    raise TypeError(message) from exc

    def _prevent_forbidden_type_annotations(cls):  # noqa: N805
        """
        Prevent forbidden type annotations for Config attributes
        """

        for field in getattr(cls, "__dataclass_fields__", {}).values():
            field_type = get_maybe_optional_type(field.type)

            # Forbid Union[Config, ...] and Tuple[Config, ...]
            if annotation_is_union(field_type) or annotation_is_tuple(field_type):
                type_args: Tuple[Type, ...] = get_annotation_type_args(field_type)

                is_config: List[bool] = [
                    inspect.isclass(arg) and isinstance(arg, ConfigMeta) for arg in type_args
                ]
                if any(is_config):
                    etype = 'Union' if annotation_is_union(field_type) else 'Tuple'
                    raise TypeError(
                        f"Class {cls} has field {field.name}: {field.type}, but {etype} with members "
                        f"of type Config are not allowed. Find a better abstraction."
                    )

                is_enum: List[bool] = [annotation_is_enum(arg) for arg in type_args]

                if sum(is_enum) > 1 and annotation_is_union(field_type):
                    raise TypeError(
                        f"Class {cls} has field {field.name}: {field.type}, "
                        f"but Union with multiple enums is not supported"
                    )

                if sum(is_enum) > 0 and annotation_is_tuple(field_type):
                    raise TypeError(
                        f"Class {cls} has field {field.name}: {field.type}, "
                        f"but Tuple with enums is not supported"
                    )
                continue

            if annotation_is_dict(field_type) or annotation_is_list(field_type):
                # Annotation type checks will be run by cls.types below
                continue
            # Forbid non-class type annotations
            if (
                not inspect.isclass(field_type)
                and not isinstance(field_type, dataclasses.InitVar)
                and field_type is not dataclasses.InitVar
                and getattr(field_type, "__origin__", None) is not ClassVar
            ):
                raise TypeError(
                    f"Forbidden type annotation in {cls} for field '{field.name}: {field.type}'. "
                    f"Expected a class, Optional[class], Dict, List, Tuple or Union"
                )


class Config(Dataclass, metaclass=ConfigMeta):
    autoclass: str = ""  # Special attribute for AutoConfig and AutoConfigurable

    def __init__(self, **kwargs):
        object.__setattr__(self, "_Config__frozen", False)

        self._set_attributes(**kwargs)
        self._init_remaining_subconfigs()
        self._cast_dict_and_list_attrs()
        self._assert_no_missing_attributes()
        self.__post_init__()
        self._freeze_mutable_attributes()
        self._assert_post_init_is_idempotent()
        # Cast dict and list attrs again to ConfigDict and ConfigList in case __post_init__ modified them
        self._cast_dict_and_list_attrs()
        self._make_type_checks()

        object.__setattr__(self, "_Config__frozen", True)

    def __post_init__(self):
        pass

    def _set_attributes(self, **kwargs):
        for key, value in kwargs.items():
            with ConfigAttributeContext(self.__class__, key):
                # 1. Make sure key is a valid attribute of Config
                if key not in self.__dataclass_fields__:
                    raise UnexpectedConfigAttributeError(
                        f"{self.__class__.__name__}.__init__() got unexpected keyword argument: "
                        f"{key}, expects one of: {list(self.__dataclass_fields__.keys())}"
                    )

                annotation_type: Type = self.__dataclass_fields__[key].type
                default_value: Any = self.__dataclass_fields__[key].default

                # 2. If annotated type is Config, recursively initialize its attributes
                if isinstance(annotation_type, ConfigMeta):
                    # 2.1 `value` is neither a Config, nor a dict -> INVALID
                    if not isinstance(value, (Config, collections.abc.Mapping)):
                        raise InvalidConfigAttributeTypeError(
                            f"{self.__class__.__name__}.{key} expects dict-like object "
                            f"(nested config), but got string/value: {value}"
                        )

                    # 2.2. `value` is already a complete Config instance -> default values don't make
                    # a difference and we can confidently set the attribute to `value`
                    if isinstance(value, Config):
                        pass

                    # 2.3. A default value is provided as a Config -> then apply `value` on top of the default
                    elif default_value != dataclasses.MISSING:
                        assert isinstance(value, collections.abc.Mapping), value
                        assert isinstance(default_value, Config), default_value

                        value = replace_with_auto_config(default_value, value)
                        assert isinstance(value, annotation_type), value

                    # 2.3 If `value` is not a Config, we make it one
                    if not isinstance(value, Config):
                        value = annotation_type(**value)

                # 3. Annotated type is Optional[Config]
                elif annotation_is_optional(annotation_type) and isinstance(
                    get_maybe_optional_type(annotation_type), ConfigMeta
                ):
                    # This is not supported yet
                    if default_value != dataclasses.MISSING and default_value is not None:
                        raise NotImplementedError(
                            f"Default values different from None are not supported for Optional[Config], "
                            f"but got {self.__class__.__name__}.{key}: {annotation_type} = {default_value}"
                        )
                    if (value is not None) and not isinstance(value, Config):
                        value = get_maybe_optional_type(annotation_type)(**value)

                # 4. Annotated type is Dict[str, Any]
                elif annotation_is_dict(annotation_type):
                    # 4.1 Make sure `value` is dict-like
                    if not isinstance(value, collections.abc.Mapping):
                        raise InvalidConfigAttributeTypeError(
                            f"{self.__class__.__name__}.{key} expects dict-like object "
                            f", but got value: {value}"
                        )
                    # 4.2. SPECIAL CASE: If `value` is empty dict, then directly overwrite the default.
                    # Otherwise there is no way to overwrite defaults
                    if value != {}:
                        # Merge the current value of the attribute with the new value.
                        # Note that Dict[str, Config] or nested versions must support
                        # initialization with dict args for `Config` so that we have proper YAML support
                        value = _update_dict_of_maybe_configs(getattr(self, key, {}), value)

                # 5. Annotated type is enum.Enum
                elif annotation_is_enum(annotation_type) and not isinstance(value, enum.Enum):
                    assert isinstance(value, str), value
                    value = annotation_type(value)

                # 6. Annotated type is Union[enum.Enum, ...]
                elif isinstance(value, str) and annotation_is_union(annotation_type):
                    union_types: Tuple[Type, ...] = get_annotation_type_args(annotation_type)
                    is_enum: List[bool] = [
                        annotation_is_enum(union_type)
                        for union_type in get_annotation_type_args(annotation_type)
                    ]
                    if any(is_enum):
                        enum_type = union_types[is_enum.index(True)]
                        value = enum_type(value)

                # 7. Autocast native types (e.g. int -> float, or list -> tuple for Tuple fields)
                else:
                    value = maybe_autocast_native_types(value, get_maybe_optional_type(annotation_type))

                setattr(self, key, value)

    @cached_classproperty
    def _cast_fields(cls) -> Dict[str, Any]:  # noqa: N805
        """
        Returns a frozendict containing only the fields annotated as Dict and List in this `Config`
        and their equivalent `ConfigDict` and `ConfigList` types that values should be cast to.
        Note that ConfigMeta already ensures that all Dict and List annotations can be cast.

        Note: we iterate over cls.fields instead of super()._cast_fields(), as the latter will materialize
        a config class with DataclassDict / DataclassList children first, which we will throw away anyway.

        Returns: Dict[str, Union[Type[ConfigDict], Type[ConfigList]]]
        """
        # pylint: disable=no-self-argument
        import ladder.core.databib.config.config_iterables as config_iterables  # pylint: disable=cyclic-import

        cast_fields: Dict[str, Type[DataclassInterface]] = {}
        for field in cls.fields.values():
            if annotation_is_dict(field.type):
                _, value_type = get_dict_annotation_type_args(field.type)
                cast_fields[field.name] = config_iterables.ConfigDict[value_type]  # type: ignore[name-defined]
            elif annotation_is_list(field.type):
                (value_type,) = get_list_annotation_type_args(field.type)
                cast_fields[field.name] = config_iterables.ConfigList[value_type]  # type: ignore[name-defined]
        return frozendict(cast_fields)

    def _init_remaining_subconfigs(self):
        """Initialize any attributes which were not passed to __init__ (maybe they have default values)"""
        for key in self.__dataclass_fields__:
            if not hasattr(self, key) and isinstance(self.__dataclass_fields__[key].type, ConfigMeta):
                with ConfigAttributeContext(self.__class__, key):
                    setattr(self, key, self.__dataclass_fields__[key].type())

    def _cast_dict_and_list_attrs(self):
        """
        Cast attributes of sel annotated as Dict or List to their corresponding immutable
        config equivalents, i.e. ConfigDict and ConfigList
        """
        for field_name, field_type in self._cast_fields.items():
            field_value = getattr(self, field_name)
            if type(field_value) is field_type:
                # If field_value is already of type DataclassDict or DataclassList,
                # then we don't need to worry about ValueT being a dataclass
                continue
            if inspect.isclass(field_type.ValueT) and issubclass(field_type.ValueT, Config):
                # Cast the values inside the Dict or the List to Config (expected Config.__init__ behavior)
                if issubclass(field_type, DataclassDict):
                    if not isinstance(field_value, collections.abc.Mapping):
                        raise TypeError(
                            f"Expected dict for field {field_name}, "
                            f"but got {field_value} of type {type(field_value)}"
                        )
                    field_value = {
                        key: field_type.ValueT(**value) if not isinstance(value, Config) else value
                        for key, value in field_value.items()
                    }
                elif issubclass(field_type, DataclassList):
                    if not isinstance(field_value, Sequence):
                        raise TypeError(
                            f"Expected dict for field {field_name}, "
                            f"but got {field_value} of type {type(field_value)}"
                        )
                    field_value = [
                        field_type.ValueT(**value) if not isinstance(value, Config) else value
                        for value in field_value
                    ]
            setattr(self, field_name, field_type(field_value))

    def _freeze_mutable_attributes(self):
        for key in self.__dataclass_fields__:
            value = getattr(self, key)
            if type(value).__name__ in _FROZEN_TYPE_MAPPING:
                setattr(self, key, _FROZEN_TYPE_MAPPING[type(value).__name__](value))

    def _assert_no_missing_attributes(self):
        all_missing_attributes = []
        for key in self.__dataclass_fields__.keys():
            if not hasattr(self, key):
                all_missing_attributes.append(key)

        if all_missing_attributes:
            with ConfigAttributeContext(self.__class__, all_missing_attributes[0]):
                raise MissingConfigAttributeError(
                    f"Fields {all_missing_attributes} of {self.__class__.__name__} were not provided"
                )

    def _assert_post_init_is_idempotent(self):
        """
        Make sure that when called twice, `self.__post_init__()` keeps references to all basic values
        instead of generating new objects. Example:
        ```
        config = Config();
        new_config = config.replace(**{})
        ```
        If __post_init__() generates any values dynamically, we want to make sure that config and new_config
        have the same dynamically generated values, i.e. config == new_config
        """
        post_init_dict = self.as_dict()
        self.__post_init__()
        self._freeze_mutable_attributes()
        twice_post_init_dict = self.as_dict()
        if post_init_dict != twice_post_init_dict:
            dict_diff = DeepDiff(post_init_dict, twice_post_init_dict)
            raise RuntimeError(
                f"{self.__class__.__name__}.__post_init__() is not idempotent: "
                f"got difference\n{pprint.pformat(dict_diff, indent=2)}"
            )

    def _make_type_checks(self):
        """
        Overload Dataclass._make_type_checks to use exact type matching, with the exception of
        AutoConfig fields, where we check that the value is an instance of the exact annotation bound
        (the resolved Config subclass). This is the same policy ConfigDict / ConfigList apply to their
        values via `_auto_config_isinstance`.
        """
        import ladder.core.databib.config.config_iterables as config_iterables  # pylint: disable=cyclic-import

        for field_name, field_type in self.types.items():
            value = getattr(self, field_name)
            with ConfigAttributeContext(self.__class__, field_name):
                if not value_type_is_annotation_type(
                    value, field_type, config_iterables._auto_config_isinstance  # noqa: SLF001
                ):
                    raise InvalidConfigAttributeTypeError(
                        f"Incorrect type provided for {self.__class__.__name__}.{field_name}: "
                        f"expected {field_type}, but got value {value} with type {type(value)}"
                    )

    @classmethod
    def make_empty(cls):
        raise NotImplementedError(f"make_empty() is disabled for Config classes ({cls.__name__})")

    @classmethod
    def from_yaml(cls, yml_path: str, save_path: bool = True):
        if not os.path.exists(yml_path):
            raise FileNotFoundError(f'File not found: "{yml_path}"')

        config_dict = load_config(yml_path)
        if config_dict is None:
            raise ValueError("Config loaded from yaml file cannot be empty.")

        if save_path and 'config_path' in cls.keys():
            return cls(**config_dict, config_path=yml_path)
        return cls(**config_dict)

    @classmethod
    def from_yaml_file_object(cls, yml_file: TextIO):
        config = load_config(yml_file)
        if config is None:
            raise ValueError("Config loaded from yaml file cannot be empty.")
        return cls(**config)

    def __config_setattr__(self, key, value):
        with ConfigAttributeContext(self.__class__, key):
            if self.__frozen:
                raise RuntimeError(
                    "Cannot set attribute '{}' to '{}' on a frozen object: {}".format(key, value, self)
                )
            if key not in self.__dataclass_fields__:
                raise UnexpectedConfigAttributeError(
                    "Cannot set attribute {} on {} as it is not one of its fields".format(
                        key, self.__class__.__name__
                    )
                )
        object.__setattr__(self, key, value)

    def as_json(self, recursive: bool = True) -> dict:
        data = super().as_json(recursive=recursive)
        # Remove autoclass_key if it's empty to avoid clutter where the field is useless
        if self.autoclass == "":
            data.pop("autoclass", None)

        # Convert enum.Enum to str
        for key, value in data.items():
            if isinstance(value, enum.Enum):
                data[key] = str(value.value)

        return data


def replace_with_auto_config(default: Config, replacements: Dict[str, Any]) -> Config:
    """
    Recursively replace `default` with `replacements`

    NOTE: This is NOT equivalent to `default.replace(**replacements)`. Consider these caveats:
    1. Let default has a field of type AutoConfig and replacements requests a different type via 'autoclass'.
        Then `default.replace` will be incorrect as it will return the same type as the current value
        of its field instead of the type specified by 'autoclass' in replacements
    2. The above cannot be always resolved by type(default)(**{**default.as_json(), **replacements}) either.
        If default has a field of type AutoConfig, but its default value is a specific Config instance,
        'autoclass' will be empty when `default.as_json()` is called and cannot be reconstructed either
        since we don't know the target Configurable type.
    """
    for key, value in replacements.items():
        if isinstance(value, collections.abc.Mapping):
            replacements[key] = replace_with_auto_config(getattr(default, key), value)  # type: ignore[arg-type]

    if replacements.get('autoclass', '') != '':
        # replacements changes the output type - we cannot call simple default.replace
        # NOTE: If the annotation is not AutoConfig, the calling function will complain
        import ladder.core.databib.config.auto_config as auto_config  # pylint: disable=cyclic-import

        output: Config = auto_config.AutoConfig(**{**default.as_json(recursive=False), **replacements})
    else:
        # Calling replace is safe since all nested dicts in replacements have been recursively
        # converted to Config instances already and replace will overwrite them directly in `default`
        output = default.replace(**replacements)

    return output


class ConfigAttributeContext:
    attr_tree: List[Tuple[ConfigMeta, str]] = []

    def __init__(self, config_class: Type[Config], attr_name: str):
        self._config_class = config_class
        self._attr_name = attr_name

    def __enter__(self):
        self.attr_tree.append((self._config_class, self._attr_name))

    def __exit__(self, exc_type, exc_val, exc_tb):
        if exc_type is None:
            self.attr_tree.pop()

    @classmethod
    def reset(cls):
        cls.attr_tree.clear()


class ConfigAttributeError(Exception):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._attr_tree = self._get_attr_tree()
        ConfigAttributeContext.reset()

    def _get_attr_tree(self):
        attr_tree = ""
        for i, (config_class, attr_name) in enumerate(ConfigAttributeContext.attr_tree):
            attr_tree += config_class.__name__ + "\n" + (i + 1) * "\t" + attr_name + ": "
        attr_tree += self.__class__.__name__
        return attr_tree

    def __str__(self):
        return super().__str__() + "\n\n" + self._attr_tree


